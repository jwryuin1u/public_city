"""공도복 매물 손익 계산기 (v0.1)

사용: python3 analysis/calc.py
아래 INPUT 값을 매물/구역에 맞게 고쳐서 실행. 단위: 억원.
"""

# ---------------- INPUT ----------------
INPUT = {
    "name": "예시: 증산4 빌라 사례(공시 2.06억, 대지지분 7.9평)",
    "매수가": 5.0,               # 호가/매수 예정가
    "공시가": 2.06,              # 2026 공동주택가격 (빌라). 모르면 None
    "대지지분_평": 7.9,           # 모르면 None
    "공시가_배율": (1.4, 1.6, 1.8),   # 감정평가액/공시가 (보수, 기준, 낙관). 증산4 사례 1.6
    "지분_평당가": 0.417,         # 억/평, 증산4 빌라 사례 4,170만
    "우선공급가": {"59": 9.55, "74": 10.19},  # 증산4 기준. 대상지 값 나오면 교체
    "완공시세": {"59": 13.5, "74": 14.5},     # 5년 뒤 기준 (사용자 가정)
    "부대비용율": 0.03,           # 취득세+중개+기타. 다주택이면 크게 올라감
    "기회비용율_연": 0.04,        # 매수 자금의 연 기회비용(단리)
    "보유연수": 5,
}
# ---------------------------------------


def run(c):
    print(f"\n=== {c['name']} ===")
    rights = {}
    if c.get("공시가"):
        for label, m in zip(("보수", "기준", "낙관"), c["공시가_배율"]):
            rights[f"공시가×{m}({label})"] = c["공시가"] * m
    if c.get("대지지분_평"):
        rights[f"지분{c['대지지분_평']}평×{c['지분_평당가']*1e4:.0f}만"] = c["대지지분_평"] * c["지분_평당가"]

    n, r, fee = c["보유연수"], c["기회비용율_연"], c["부대비용율"]
    buy = c["매수가"]
    cost_buy = buy * (1 + fee + r * n)
    print(f"매수가 {buy:.2f} → 부대비용·기회비용 포함 {cost_buy:.2f}")

    for rl, right in rights.items():
        print(f"\n[권리가액 {rl} = {right:.2f}]  프리미엄 = {buy - right:+.2f}")
        print(f"  {'타입':<4}{'우선공급가':>9}{'분담금':>8}{'완공시세':>9}{'안전마진':>9}{'기대차익':>9}{'손익분기 매수가':>14}")
        for t, price in c["우선공급가"].items():
            mkt = c["완공시세"][t]
            levy = price - right
            margin = mkt - price
            profit = mkt - (cost_buy + levy)
            breakeven = (mkt - levy) / (1 + fee + r * n)
            print(f"  {t:<4}{price:>11.2f}{levy:>10.2f}{mkt:>11.2f}{margin:>11.2f}{profit:>11.2f}{breakeven:>16.2f}")


if __name__ == "__main__":
    run(INPUT)
